// npm run build:hm  ->  ../public/hm/ (loader.js, machine.js, machine.css) and demo/ (host page and test pages,
// git-ignored). The posters in public/hm/ come from make-posters.mjs.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildB } from "./src/variant-b.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(HERE, p), "utf8");
const OUT = join(HERE, "..", "public", "hm");
const HEADER = "// Generated by frontend/how-it-works/build.mjs; edit frontend/how-it-works/src/ instead.";
mkdirSync(OUT, { recursive: true });
mkdirSync(join(HERE, "demo"), { recursive: true });

const CSS = read("src/machine.css");
const MODEL = read("src/model.mjs").replace(/^export /gm, "");
const RUNTIME = read("src/runtime.js");

export const ALT =
  "An illustrated machine shows how Higgins turns one sentence into a plan. A paper ticket that reads “Wedding for 300 in Jaipur, about ₹25 lakh” drops into a brass hopper. Coins, standing for the budget, roll down a chute into four tanks labelled Venue, Food, Décor and Other, and how full each tank gets shows the split. A calendar drum turns to the wedding month, and book-by tags move along a rail to show how far ahead to book each part. A plan card slides out toward a phone that shows the plan and a Send to family button. Two levers change the example, +25 guests and Move the date, and a reset button goes back to the start. All numbers are examples.";

function art(v) {
  const hits = v.order.map((id) => v.hits.find((h) => h.id === id)).filter(Boolean);
  const buttons = v.hits.filter((h) => h.button);
  const partHits = hits.map((h, i) => `<path class="hm-hit" data-hit="${h.id}" tabindex="${i === 0 ? 0 : -1}" role="img" aria-roledescription="machine part" d="${h.d}"/>`).join("");
  const buttonHits = buttons.map((h) => `<path class="hm-hit" data-hit="${h.id}" data-button="${h.button}" tabindex="0" role="button" aria-label="${h.label}" d="${h.d}"/>`).join("");
  const back = `<svg class="iso-svg hm-back" viewBox="0 0 ${v.W} ${v.H}" aria-hidden="true" focusable="false"><g>${v.body.join("")}</g></svg>`;
  const svg = `<svg class="iso-svg hm-live" viewBox="0 0 ${v.W} ${v.H}" role="group" aria-labelledby="hm-${v.data.id}-t" aria-describedby="hm-${v.data.id}-d"><title id="hm-${v.data.id}-t">How Higgins turns one sentence into a plan, as a machine</title><defs>${v.defs.join("")}</defs><g aria-hidden="true">${v.live.join("")}</g><g class="hm-hits" role="group" aria-label="Machine parts and controls. Arrow keys move between parts.">${partHits}${buttonHits}</g></svg>`;
  return `<figure class="hm-card iso">
<span class="hm-corner" data-corner="fig" aria-hidden="true">Example</span>
<span class="hm-corner" data-corner="title" aria-hidden="true">One sentence in, a plan out</span>
<span class="hm-corner" data-corner="hint" aria-hidden="true">Pull a lever to change the example</span>
<span class="hm-corner" data-corner="readout" data-readout aria-hidden="true"></span>
<div class="hm-stage">${back}${svg}<div class="hm-tip" aria-hidden="true"></div></div>
<figcaption class="hm-legend" data-legend></figcaption>
<p class="hm-sr" id="hm-${v.data.id}-d">${ALT}</p>
<p class="hm-sr" aria-live="polite" data-live></p>
</figure>`;
}

const v = buildB();
const data = { ...v.data, tankW: v.data.tankW ?? 18 };
const module = `// Higgins: "See how it works" machine. ${HEADER.slice(3)}
const D = ${JSON.stringify(data)};
const ART = ${JSON.stringify(art(v))};
${MODEL}
${RUNTIME}
export const ratio = ${v.W} / ${v.H};
`;
writeFileSync(join(OUT, "machine.js"), module);
// Linked by the runtime and the poster, never inlined, so the page can keep style-src 'self'.
writeFileSync(join(OUT, "machine.css"), `/* ${HEADER.slice(3)} */
${CSS}`);
const paths = (art(v).match(/<path/g) || []).length;
console.log(`machine.js  ${(module.length / 1024).toFixed(0)} KB raw, ${paths} paths`);

// The loader: a tiny custom element that shows the poster on narrow screens and
// imports the live machine only when it nears the viewport on wider ones.
writeFileSync(join(OUT, "loader.js"), `${HEADER}
${read("src/loader.js")}`);

